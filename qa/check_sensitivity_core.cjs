const assert=require('node:assert/strict');
const M=require('../src/methods_core.js');
const S=require('../src/sensitivity_core.js');
const rectangle=(x,y,w,h=w)=>[[x,y],[x+w,y],[x+w,y+h],[x,y+h]];
const section=(id,z,paths=[rectangle(0,0,32)])=>({id,order:z,z,rois:[{paths}]});
const constant={unit:'index',sections:[section('first',0),section('middle',3),section('last',10)]};
const before=JSON.stringify(constant),r=S.run(constant,{gridSize:96});
assert.equal(JSON.stringify(constant),before);
assert.deepEqual(r,S.run(constant,{gridSize:96}));
// Analytic rectangle exactly aligns with the 0.5-coordinate grid.
assert.deepEqual(r.baseline,{sdf:32*32*10,affine:32*32*10});
assert.equal(r.boundary.sdf.lower,31*31*10);
assert.equal(r.boundary.sdf.upper,33*33*10);
assert.deepEqual(r.config.fixed_z_mesh,[0,1,3,6,10]);
assert.deepEqual(r.config.interval_widths,[1,2,3,4]);
assert.equal(r.influence[1].methods.sdf.delta_percent,0);
assert.equal(r.influence[1].methods.sdf.threshold_crossed,false);
assert.equal(r.influence[0].status,'excluded_from_influence');
assert.equal(r.influence[2].status,'excluded_from_influence');
assert.equal(r.influence[0].methods.sdf.value,null);
assert.equal(r.influence[2].methods.sdf.delta_percent,null);
assert.deepEqual(r.influence[1].profile.map(p=>p.z),r.profile.map(p=>p.z));
assert.equal(r.influence[1].profile.find(p=>p.z===3).kind,'predicted');
assert.ok(r.influence[1].profile.filter(p=>p.kind==='predicted').every(p=>!p.training_ids.includes('middle')));
for(const p of r.influence[1].profile.filter(p=>p.kind==='observed'))assert.deepEqual(p,r.profile.find(q=>q.id===p.id));
const unequal={unit:'um',sections:[section('u1',0),{...section('u2',1),z:2.5},{...section('u3',2),z:17.25}]};
const physical=S.run(unequal,{gridSize:96});
assert.equal(physical.baseline.sdf,1024*17.25);
assert.deepEqual(physical.config.fixed_z_mesh,[0,1.25,2.5,9.875,17.25]);
assert.equal(physical.config.integral_unit,'input_XY_squared_times_um');
const adjacent=S.run({unit:'index',sections:[section('a',0),section('b',1),section('c',2)]},{gridSize:96});
assert.deepEqual(adjacent.config.fixed_z_mesh,[0,1,2]);
const enlarged=structuredClone(constant);enlarged.sections[1].rois[0].paths=[rectangle(0,0,48,32)];
const e=S.run(enlarged,{gridSize:96,thresholdPercent:5});
for(const name of ['sdf','affine']){assert.ok(e.influence[1].methods[name].delta_percent < -10);assert.equal(e.influence[1].methods[name].threshold_crossed,true);}
assert.ok(e.method_difference_percent>0);
assert.equal(S.run(enlarged,{gridSize:96,thresholdPercent:100}).influence[1].methods.sdf.threshold_crossed,false);
// Held-out geometry changes scores only, never predictor masks or its grid.
const training={unit:'index',sections:[constant.sections[0],constant.sections[2]]};
const p=M.predict(training,3,{gridSize:96}),predBefore=JSON.stringify(p);
assert.equal(M.evaluate(p,constant.sections[1]).scores.sdf.dice,1);
const moved=section('middle',3,[rectangle(100,0,32)]);
const outside=M.evaluate(p,moved);
assert.equal(outside.scores.sdf.dice,0);
assert.equal(outside.scores.sdf.false_negative,outside.scores.sdf.truth_count);
assert.ok(outside.truth_outside_count>0);
assert.equal(JSON.stringify(p),predBefore);
assert.equal(M.evaluate(p,moved,{evaluationCellLimit:1024}).scores,null);
assert.equal(M.evaluate(p,moved,{evaluationCellLimit:1024}).status,'unscorable');
assert.throws(()=>M.evaluate(p,{...constant.sections[1],id:'first'}),/training/);
assert.throws(()=>M.evaluate(p,{...constant.sections[1],z:4}),/depth/);
assert.throws(()=>M.predict(training,11),/Extrapolation/);
assert.throws(()=>M.predict(training,2.5),/integer/);
assert.throws(()=>M.predict(training,0),/unobserved/);
const clipped={unit:'index',sections:[{id:'l',order:0,z:0,rois:[{paths:[rectangle(0,0,20)]},{paths:[rectangle(50,0,2)]}]},section('m',2,[rectangle(0,0,100)]),section('r',4,[rectangle(0,0,100)])]};
const clipping=S.run(clipped,{gridSize:96});
assert.equal(clipping.baseline_status,'unscorable');
assert.equal(clipping.baseline.affine,null);
assert.equal(clipping.boundary.affine.upper,null);
assert.ok(clipping.profile.some(p=>p.flags.includes('aligned_source_outside_prediction_grid')));
assert.equal(clipping.influence[1].methods.affine.delta_percent,null);
assert.equal(clipping.influence[1].methods.affine.threshold_crossed,null);
assert.throws(()=>S.run(constant,{gridSize:32}),/grid/);
assert.throws(()=>S.run(constant,{thresholdPercent:0}),/percentage/);
assert.throws(()=>S.run({...constant,sections:[constant.sections[0],constant.sections[0],constant.sections[2]]}),/unique/);
assert.throws(()=>S.run({...unequal,sections:unequal.sections.map((s,i)=>i===1?{...s,z:null}:s)}),/missing/);
const empty=structuredClone(constant);empty.sections[1].rois[0].paths=[rectangle(0,0,1e-8,32)];
const missing=S.run(empty,{gridSize:96});
assert.equal(missing.baseline.sdf,null);
assert.equal(missing.baseline_status,'unscorable');
assert.ok(missing.profile.some(p=>p.flags.includes('observation_empty_at_grid_resolution')));
const underflow={unit:'um',sections:[0,1,2].map(n=>({id:'p'+n,order:n,z:n*1e-160,rois:[{paths:[rectangle(0,0,1e-100)]}]}))};
const tinyIntegral=S.run(underflow);
assert.equal(tinyIntegral.baseline.sdf,null);
assert.equal(tinyIntegral.baseline_status,'unscorable');
assert.ok(tinyIntegral.profile.some(p=>p.flags.includes('integral_numeric_underflow')));
// Empty interpolated masks are measured algorithm outputs, unlike a vanished
// observed polygon. Keeping their zero area exposes interpolation failure.
const shifted={unit:'index',sections:[section('p0',0),section('p1',4,[rectangle(100,0,32)]),section('p2',8)]};
const emptyPrediction=S.run(shifted,{gridSize:96});
assert.equal(emptyPrediction.baseline.sdf,4096);
assert.equal(emptyPrediction.profile.find(p=>p.z===2).area.sdf,0);
assert.ok(emptyPrediction.profile.find(p=>p.z===2).flags.includes('empty_prediction'));
console.log('SensitivityCore: fixed-span analytic integrals, boundary perturbation, unequal depth, omission influence, chosen tolerance, immutable input, no held-out leakage, clipped/vanished-observation/underflow null values, and flagged zero-area predictions passed.');
