#!/usr/bin/env python3
"""Writes editable-roi-reference.json: what scripts/roi_editable.py gives on synthetic labels. The JavaScript core in
src/editable_roi_core.js must give the same polygons and layers (qa/check_editable_roi_core.cjs). Run from the
repository root after changing either implementation on purpose; the file is not regenerated by the checks."""
import json
import sys
import tempfile
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
import roi_draft as D  # noqa: E402
import roi_editable as E  # noqa: E402
import roi_measure as M  # noqa: E402
from nissl_lab import read_roi_zip  # noqa: E402

H, W, UM2 = 300, 500, 1 / 1.96


def labels():
    out = np.zeros((H, W), np.uint8)
    yy, xx = np.mgrid[:H, :W]
    out[(xx - 230) ** 2 / 200 ** 2 + (yy - 150) ** 2 / 120 ** 2 <= 1] = 1
    out[(xx - 230) ** 2 / 150 ** 2 + (yy - 150) ** 2 / 80 ** 2 <= 1] = 2
    out[(xx - 200) ** 2 / 90 ** 2 + (yy - 160) ** 2 / 40 ** 2 <= 1] = 3
    out[(xx - 330) ** 2 / 25 ** 2 + (yy - 150) ** 2 / 25 ** 2 <= 1] = 3     # a second island of white matter
    out[(xx - 150) ** 2 / 12 ** 2 + (yy - 70) ** 2 / 12 ** 2 <= 1] = 0      # a hole in the tissue
    out[240:285, 440:490] = 1                                              # a separate part
    out[250:275, 450:480] = 2                                              # with its own granular layer
    out[10:16, 470:476] = 1                                                # a speck
    return out


def main():
    protocol, plain = M.load_protocol(), dict(D.PARAMETERS, pl_band_width_um=0.0)
    rois, _ = D.draft_rois(labels(), protocol, plain)
    with tempfile.TemporaryDirectory() as temporary:
        path = Path(temporary) / 'usual.zip'
        path.write_bytes(D.roi_zip_bytes(rois))
        usual, _ = read_roi_zip(path)
        cases = {}
        for key, limit in (('all', 0.0), ('default', E.PARAMETERS['drop_secondary_parts_below_um2']), ('roomy', 600.0)):
            parameters = dict(E.PARAMETERS, drop_secondary_parts_below_um2=limit)
            polygons, summary = E.editable(usual, H, W, parameters, UM2)
            cases[key] = {'parameters': parameters, 'um2': UM2,
                          'polygons': [{'name': q['name'], 'kind': q['kind'], 'path': q['paths'][0]} for q in polygons],
                          'summary': {k: {a: v[a] for a in ('parts', 'separate_parts_before', 'holes', 'vertices_before', 'vertices_after') if a in v}
                                      for k, v in summary.items()}}
        path = Path(temporary) / 'editable.zip'
        path.write_bytes(E.editable_zip(E.editable(usual, H, W, dict(E.PARAMETERS, drop_secondary_parts_below_um2=0.0), UM2)[0]))
        edited, _ = read_roi_zip(path)
        back = {}
        for key, band in (('no_band', 0.0), ('band20', 20.0)):
            built, _, structure, how = E.rebuild(edited, H, W, protocol, dict(D.PARAMETERS, pl_band_width_um=band))
            named = {r['name']: r for r in built}
            pairs = (('CB', 'Cb'), ('ML', 'ML_TOTAL'), ('GL', 'GL_TOTAL'), ('WM', 'WM'))
            back[key] = {'pl_band_width_um': band, 'band_pixels': structure['purkinje_band']['pixels'],
                         'areas_px': {k: int(M.area_px2(named[v])) for k, v in pairs}, 'rings': {k: named[v]['paths'] for k, v in pairs},
                         'clipped': how['clipped_to_keep_layers_nested']}
        named = {r['name']: r for r in usual}
        fixture = {'note': 'Made by scripts/roi_editable.py on synthetic labels; the JavaScript core must give the same polygons and layers.',
                   'width': W, 'height': H, 'pixels_per_micron': 1.4,
                   'layers': {k: named[v]['paths'] for k, v in (('CB', 'Cb'), ('GL', 'GL_TOTAL'), ('WM', 'WM'))}, 'pl': named['PL_TOTAL']['paths'][0],
                   'export': cases, 'edited': [{'name': r['name'], 'kind': r['kind'], 'paths': r['paths']} for r in edited], 'rebuild': back}
    (Path(__file__).resolve().parent / 'editable-roi-reference.json').write_text(json.dumps(fixture, separators=(',', ':')) + '\n')
    print({k: len(v['polygons']) for k, v in cases.items()}, {k: v['areas_px'] for k, v in back.items()})


main()
