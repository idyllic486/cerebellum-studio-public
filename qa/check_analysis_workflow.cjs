'use strict';
const assert=require('node:assert/strict'),C=require('../src/analysis_workflow_core.js');
const find=(c,id)=>C.suggestions(c).find(x=>x.id===id);
assert.equal(find({},'source').available,true);
assert.equal(find({hasSource:true},'model').available,true);
assert.equal(find({hasSource:true},'model').target,'analysisModel');
assert.equal(find({hasSource:true,busy:true},'model').available,false);
assert.equal(find({hasSource:true,modelReady:true},'model').target,'analysisGenerate');
const draft={hasSource:true,hasReview:true,roiCount:2,calibrated:false,hasZ:false,approved:false};
assert.equal(find(draft,'study').available,false);
assert.equal(find(draft,'calibration').target,'analysisScaleX');
const approved={...draft,approved:true};
assert.equal(find(approved,'archive').available,true);
assert.match(find(approved,'study').detail,/measured XY, actual Z/);
assert.equal(find({...approved,pending:true},'archive'),undefined);
assert.equal(find({...approved,pending:true},'study').available,false);
assert.equal(find({...approved,busy:true},'study').available,false);
assert.match(find({...approved,calibrated:true,hasZ:true},'study').detail,/One section does not establish volume/);
assert.equal(find({...draft,roiCount:0},'approval').available,false);
assert.equal(find({...draft,hasCSV:true},'reference').target,'analysisCSVFile');
let now=0;const clock=C.createClock(()=>now);
clock.start();now=10000;assert.equal(clock.snapshot().elapsed_ms,10000);
clock.block(true);now=45000;assert.equal(clock.snapshot().elapsed_ms,10000);
clock.block(false);now=50000;assert.equal(clock.snapshot().elapsed_ms,10000);
clock.activity();now=55000;assert.equal(clock.snapshot().elapsed_ms,15000);
now=150000;assert.equal(clock.snapshot().elapsed_ms,70000);assert.equal(clock.snapshot().active,false);
clock.activity();now=155000;clock.pause();assert.equal(clock.snapshot().elapsed_ms,75000);
now=300000;assert.equal(clock.snapshot().elapsed_ms,75000);
clock.start();now=310000;assert.equal(clock.snapshot().elapsed_ms,85000);
clock.reset();assert.equal(clock.snapshot().elapsed_ms,0);assert.equal(clock.snapshot().recording,false);
console.log('Analysis workflow: input-dependent actions, approval/pending gates, no one-section volume claim; timing excludes processing, inactive intervals and idle gaps.');
